import assert from 'node:assert/strict';
import { billingReturnMessage, clearCheckoutIntent, isTrustedBillingUrl, retainCheckoutIntent } from '../src/utils/coreBillingView.js';
const items=new Map();
const storage={getItem:key=>items.get(key),setItem:(key,value)=>items.set(key,value),removeItem:key=>items.delete(key)};
let issued=0;
const next=()=>`checkout-intent-${++issued}`;
const first=retainCheckoutIntent('parent-one',storage,next);
assert.equal(retainCheckoutIntent('parent-one',storage,next),first);
assert.notEqual(retainCheckoutIntent('parent-two',storage,next),first);
clearCheckoutIntent('parent-one',storage);
assert.notEqual(retainCheckoutIntent('parent-one',storage,next),first);
const unavailable={getItem:()=>{throw new Error('unavailable');},setItem:()=>{throw new Error('unavailable');},removeItem:()=>{throw new Error('unavailable');}};
assert.doesNotThrow(()=>retainCheckoutIntent('parent-one',unavailable,next));
assert.doesNotThrow(()=>clearCheckoutIntent('parent-one',unavailable));
assert(isTrustedBillingUrl('https://checkout.stripe.com/c/pay/cs_test_example','checkout'));
assert(isTrustedBillingUrl('https://billing.stripe.com/p/session/test_example','portal'));
for(const value of ['javascript:alert(1)','https://checkout.stripe.com.evil.test/','https://evil.test','http://checkout.stripe.com/','https://user:password@checkout.stripe.com/','https://billing.stripe.com/p/session/test_example'])assert(!isTrustedBillingUrl(value,'checkout'));
assert.match(billingReturnMessage('?billing=success'),/after billing confirmation/);
assert.match(billingReturnMessage('?billing=canceled'),/unchanged/);
assert.equal(billingReturnMessage('?billing=unknown'),'');
console.log('Billing view: scoped exact intent retry, storage failure, trusted provider URLs and non-authoritative redirects passed.');
